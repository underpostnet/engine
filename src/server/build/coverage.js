/**
 * The coverage HTML report as a build artifact: where a run leaves it, where an assembled
 * deploy artifact carries it, and what is published when nothing was carried.
 *
 * The report is produced by the test stage (`npm run test:coverage`) and bundled into the
 * deploy artifact at {@link COVERAGE_BUNDLE_DIRECTORY}. A workload container only ever
 * copies it: running a test runner inside a pod costs minutes of the build phase, needs the
 * dev dependency tree, and — because a suite's expected non-zero exits latch the runtime
 * status contract — publishes a false `error` to the deployment monitor.
 *
 * @module src/server/build/coverage.js
 * @namespace UnderpostCoverage
 */

import fs from 'fs-extra';
import { UNDERPOST_TESTING } from './testing.js';

/**
 * @constant COVERAGE_BUNDLE_DIRECTORY
 * @description Path, relative to a source tree root, where an assembled deploy artifact
 * carries the report. Deliberately not under `coverage/`, which every engine `.gitignore`
 * excludes, so the bundled artifact is publishable source rather than a local run's output.
 * @memberof UnderpostCoverage
 */
const COVERAGE_BUNDLE_DIRECTORY = 'docs/coverage';

const normalizeRoot = (root) => `${root ?? ''}`.replace(/\/+$/, '');

/**
 * @method coverageReportCandidates
 * @description Every place a coverage HTML report can live in a source tree, most local
 * first: the reporters a run writes, then the bundled artifact a deploy artifact carries.
 * @param {string} root - Source tree root.
 * @returns {string[]} Candidate report directories.
 * @memberof UnderpostCoverage
 */
const coverageReportCandidates = (root) => {
  const base = normalizeRoot(root);
  if (!base) return [];
  const coverage = `${base}/${UNDERPOST_TESTING.coverageDirectory}`;
  return [`${coverage}/html`, `${coverage}/lcov-report`, coverage, `${base}/${COVERAGE_BUNDLE_DIRECTORY}`];
};

/**
 * @method resolveCoverageReportPath
 * @description First candidate that actually carries an HTML index. A directory holding
 * only `lcov.info` is not a report and is not published.
 * @param {string} root - Source tree root.
 * @returns {string|undefined} Report directory, or undefined when none is available.
 * @memberof UnderpostCoverage
 */
const resolveCoverageReportPath = (root) =>
  coverageReportCandidates(root).find((candidate) => fs.existsSync(`${candidate}/index.html`));

/**
 * @method bundleCoverageReport
 * @description Copies the report of `fromRoot` into `toRoot`'s bundle directory, so the
 * assembled artifact carries it into every container started from that source.
 * @param {string} fromRoot - Tree the report was generated in.
 * @param {string} toRoot - Assembled artifact root.
 * @returns {{bundled: boolean, from?: string, to: string}} What was bundled, and where.
 * @memberof UnderpostCoverage
 */
const bundleCoverageReport = (fromRoot, toRoot) => {
  const to = `${normalizeRoot(toRoot)}/${COVERAGE_BUNDLE_DIRECTORY}`;
  const from = resolveCoverageReportPath(fromRoot);
  if (!from) return { bundled: false, to };
  fs.emptyDirSync(to);
  fs.copySync(from, to);
  return { bundled: true, from, to };
};

/**
 * @method coverageUnavailablePage
 * @description The page served where a report was expected but none was bundled. A static
 * document, never an invitation to generate one at runtime.
 * @param {object} [options]
 * @param {string} [options.command] - Command that produces the report.
 * @returns {string} HTML document.
 * @memberof UnderpostCoverage
 */
const coverageUnavailablePage = ({ command = 'npm run test:coverage' } = {}) => `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="robots" content="noindex" />
    <title>Coverage report unavailable</title>
    <style>
      :root { color-scheme: light dark; }
      body { margin: 0; display: grid; place-items: center; min-height: 100vh;
             font: 16px/1.6 system-ui, -apple-system, Segoe UI, Roboto, sans-serif; }
      main { max-width: 34rem; padding: 2rem; }
      h1 { font-size: 1.25rem; margin: 0 0 .75rem; }
      p { margin: 0 0 .75rem; opacity: .8; }
      code { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; font-size: .9em; }
    </style>
  </head>
  <body>
    <main>
      <h1>Coverage report unavailable</h1>
      <p>This build carried no coverage report. The report is generated by the test stage and
      bundled into the deploy artifact under <code>${COVERAGE_BUNDLE_DIRECTORY}</code>.</p>
      <p>Run <code>${command}</code> in the build environment, then assemble and publish the
      artifact again.</p>
    </main>
  </body>
</html>
`;

export {
  COVERAGE_BUNDLE_DIRECTORY,
  bundleCoverageReport,
  coverageReportCandidates,
  coverageUnavailablePage,
  resolveCoverageReportPath,
};
